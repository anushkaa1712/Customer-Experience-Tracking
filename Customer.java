package CX;

public class Customer {
    String username;
    String password;
    String name;
    String email;
    String phone;

    Customer(String username, String password, String name, String email, String phone) {
        this.username = username;
        this.password = password;
        this.name = name;
        this.email = email;
        this.phone = phone;
    }
}
